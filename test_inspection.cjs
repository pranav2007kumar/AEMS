const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const nodes=new Map(),store=new Map();
const get=k=>{if(!nodes.has(k))nodes.set(k,{innerHTML:'',textContent:'',value:'',checked:false,style:{}});return nodes.get(k)};
const ctx={Intl,Date,console,crypto:require('node:crypto').webcrypto,setTimeout:()=>0,clearTimeout(){},location:{hash:'#home'},window:{addEventListener(){},scrollTo(){}},document:{querySelector:get,querySelectorAll:()=>[]},localStorage:{getItem:k=>store.get(k),setItem:(k,v)=>store.set(k,v)}};
vm.createContext(ctx);vm.runInContext(fs.readFileSync(__dirname+'/dist/app.js','utf8'),ctx);
vm.runInContext("security();scan(false)",ctx);
assert.match(get('#gate-result').innerHTML,/inspection-verified/);
get('#guard-verified').checked=true;get('#confirm-passage').onclick();
assert.equal(JSON.parse(store.get('amrita-visits-v1'))[0].status,'approved');
assert.match(get('#toast').textContent,/physical vehicle inspection/);
get('#inspection-verified').checked=true;get('#confirm-passage').onclick();
assert.equal(JSON.parse(store.get('amrita-visits-v1'))[0].status,'inside');
assert.equal(JSON.parse(store.get('amrita-visits-v1'))[0].inspectionConfirmed,true);
assert.ok(JSON.parse(store.get('amrita-audit-v1')).some(l=>l.action==='Physical inspection confirmed'));
vm.runInContext("gate='exit';security();scan(false)",ctx);
assert.doesNotMatch(get('#gate-result').innerHTML,/id="confirm-passage"/);
console.log('Inspection: entry blocked without inspection; confirmation logged; exit still requires warden approval.');
