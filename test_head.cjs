const assert=require('node:assert/strict');
const E=require('./dist/head-engine.js');
const now=new Date('2026-10-11T08:00:00Z'),data=E.fixtures(now);
const query=E.parse('visitor vans last Tuesday night',now);
assert.deepEqual(query.filters,{from:'2026-10-06',to:'2026-10-06',startHour:18,endHour:6,vehicleType:'Van'});
assert.ok(E.parse('show suspicious red cars',now).error);
assert.ok(E.parse('last Tuesday',new Date('2026-10-06T08:00:00Z')).filters.from==='2026-09-29');
const result=E.filter(data.visits,query.filters);
assert.ok(result.every(v=>v.vehicleType==='Van'&&E.day(v.entered)==='2026-10-06'&&(E.hour(v.entered)>=18||E.hour(v.entered)<6)));
assert.equal(E.forecast([],now).bars.length,0);
assert.equal(E.forecast(data.visits,now).days,14);
assert.ok(E.anomalies(data.visits,now).some(a=>a.id.endsWith(':dwell')));
assert.equal(E.queue(8,1,150).waitMinutes,20);
assert.equal(E.queue(8,2,150).waitMinutes,10);
assert.equal(E.queue(0,1,150).waitMinutes,0);
assert.equal(E.day('2026-10-10T20:00:00Z'),'2026-10-11');
const facts=E.facts(data.visits,data.logs,E.day(now),E.anomalies(data.visits,now));
assert.equal(facts[0].text.split(' ')[0],String(data.visits.filter(v=>E.day(v.entered)===E.day(now)).length));
console.log('Head analytics: date parsing, retrieval, forecast, anomalies, queue and grounded facts passed.');
